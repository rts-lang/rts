use crate::parser::structure::structure::Structure;
use crate::parser::testing::{checkStructure, runCode};
use std::sync::{Arc, RwLock};
// =================================================================================================

// Тесты на анонимную структуру `{ ... }` (голая форма - без имени).
//
// Имени нет - вызвать структуру нечем. Значит тело обязано прочитаться сразу.
// Иначе код внутри мёртвый.

// =================================================================================================
// Анонимная структура.

/// Анонимная структура в одну строку: тело читается сразу.
#[test]
fn anonymousStructureOneLine() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    { b = 1 }
    "#,
    "b", value "1"
  );
}

/// Анонимная структура многострочная: `{` открывает тело ниже.
#[test]
fn anonymousStructureMultiLine() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    {
      b = 1
    }
    "#,
    "b", value "1"
  );
}

/// Код после анонимной структуры не съедается: тело прочитано - чтение идёт дальше.
#[test]
fn codeAfterStructure() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    {
      b = 1
    }
    b = b + 1
    "#,
    "b", value "2"
  );
}

// =================================================================================================
// Именованная структура.

/// Именованная структура при объявлении не стартует сама: имя есть - вызов
/// возможен, поэтому она ждёт вызова (как и раньше).
#[test]
fn namedStructureDoesNotStart() -> ()
{
  let mainLink: Arc<RwLock<Structure>> = runCode!(r#"
    b~: U8 = 0
    name {
      b = 1
    }
  "#
  );

  // Тело не запускалось: `b` остался нулём.
  checkStructure!(mainLink, "b", value "0");
  // Но структура создана и вызов возможен.
  checkStructure!(mainLink, "name", stype Method);
}

/// Именованная структура запускается явным вызовом -
/// инвариант не сломан анонимным путём.
#[test]
fn namedStructureStartsByCall() -> ()
{
  let mainLink: Arc<RwLock<Structure>> = runCode!(r#"
    b~: U8 = 0
    name {
      b = 1
    }
    name()
  "#
  );

  checkStructure!(mainLink, "b", value "1");
}

