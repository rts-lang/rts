use crate::parser::testing::checkStructure;
// =================================================================================================

// Тесты на цепочку `?` (if, elif, else): какая ветка выбирается и где цепочка заканчивается.
//
// Что считается True (примитивы, константы, сравнения, пустота) проверяется в `conditions.rs`;
// блок как значение (`a := ? True { = 20 }`) проверяется в `ifEqual.rs`.
//
//
// Как проверить, в какой блок попал код: ветка меняет структуру выше в родителе,
// поэтому значение `b` после выполнения и есть ответ теста.
//
//
// Цепочка:
//
//     ? условие { }   if
//     ? условие { }   elif, сколько угодно
//     ? { }           else; всегда последний, после него начинается новая цепочка

// =================================================================================================
// if.

/// `if`: условие True — блок выполняется.
#[test]
fn ifTrue() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    ? True { b = 1 }
    "#,
    "b", value "1"
  );
}

/// `if`: условие False — блок не выполняется.
#[test]
fn ifFalse() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    ? False { b = 1 }
    "#,
    "b", value "0"
  );
}

// =================================================================================================
// if-else.

/// `if-else`: True — выполняется `if` и пропускается `else`; False — выполняется `else`.
#[test]
fn ifElse() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    ? True { b = 1 }
    ? { b = 2 }
    "#,
    "b", value "1"
  );
  checkStructure!(
    r#"
    b~: U8 = 0
    ? False { b = 1 }
    ? { b = 2 }
    "#,
    "b", value "2"
  );
}

// =================================================================================================
// if-elif.

/// `if-elif`: `elif` выполняется, только если `if` ложный; если ложны оба — ничего не выполняется.
#[test]
fn ifElif() -> ()
{
  checkStructure!(
    r#"
    n := 1
    b~: U8 = 0
    ? n = 1 { b = 1 }
    ? n = 2 { b = 2 }
    "#,
    "b", value "1"
  );
  checkStructure!(
    r#"
    n := 2
    b~: U8 = 0
    ? n = 1 { b = 1 }
    ? n = 2 { b = 2 }
    "#,
    "b", value "2"
  );
  checkStructure!(
    r#"
    n := 3
    b~: U8 = 0
    ? n = 1 { b = 1 }
    ? n = 2 { b = 2 }
    "#,
    "b", value "0"
  );
}

// =================================================================================================
// if-elif-else.

/// `if-elif-else`: выполняется одна ветка — первая с True; `else` — когда ложны все условия.
#[test]
fn ifElifElse() -> ()
{
  checkStructure!(
    r#"
    n := 1
    b~: U8 = 0
    ? n = 1 { b = 1 }
    ? n = 2 { b = 2 }
    ? { b = 3 }
    "#,
    "b", value "1"
  );
  checkStructure!(
    r#"
    n := 2
    b~: U8 = 0
    ? n = 1 { b = 1 }
    ? n = 2 { b = 2 }
    ? { b = 3 }
    "#,
    "b", value "2"
  );
  checkStructure!(
    r#"
    n := 3
    b~: U8 = 0
    ? n = 1 { b = 1 }
    ? n = 2 { b = 2 }
    ? { b = 3 }
    "#,
    "b", value "3"
  );
}

// =================================================================================================
// Границы цепочки.

/// `else` завершает цепочку: `?` после него — это новая цепочка, а не `elif`.
#[test]
fn elseEndsChain() -> ()
{
  checkStructure!(
    r#"
    n := 1
    b~: U8 = 0
    ? n = 1 { b = 1 }
    ? { b = 2 }
    ? n = 1 { b = 3 }
    "#,
    "b", value "3"
  );
}

/// `else` в начале цепочки тоже завершает её: `?` после него — новая цепочка.
#[test]
fn elseFirstEndsChain() -> ()
{
  checkStructure!(
    r#"
    n := 1
    b~: U8 = 0
    ? { b = 1 }
    ? n = 1 { b = 2 }
    "#,
    "b", value "2"
  );
}

/// Блок без условия - это обычный `else` - а они всегда выполняются.
#[test]
fn elseWithoutIf() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    ? { b = 1 }
    "#,
    "b", value "1"
  );
}

/// Строка без `?` разрывает цепочку: `?` после неё — новая цепочка, а не `elif`.
#[test]
fn lineBreaksChain() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    ? True { b = 1 }
    c := 5
    ? True { b = 2 }
    "#,
    "b", value "2"
  );
}

/// Пустое тело ветки остаётся веткой: цепочка на нём останавливается.
#[test]
fn emptyBody() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    ? True {}
    ? { b = 1 }
    "#,
    "b", value "0"
  );
  checkStructure!(
    r#"
    b~: U8 = 0
    ? False { b = 1 }
    ? {}
    "#,
    "b", value "0"
  );
}

// =================================================================================================
// Вложенность.

/// `else` вложенной цепочки принадлежит ей, а не внешней.
#[test]
fn nestedElse() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    ? True {
      ? False { b = 1 }
      ? { b = 2 }
    }
    "#,
    "b", value "2"
  );
}

/// Если во вложенной цепочке ничего не выполнилось, `else` внешней цепочки всё равно пропускается.
#[test]
fn nestedSkippedKeepsOuterElse() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    ? True {
      ? False { b = 1 }
    }
    ? { b = 9 }
    "#,
    "b", value "0"
  );
}

/// Блок `else` может содержать свою цепочку.
#[test]
fn nestedInElse() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    ? False { b = 1 }
    ? {
      ? True { b = 2 }
    }
    "#,
    "b", value "2"
  );
}

/// Вложенная цепочка с `elif` не смешивается с внешней.
#[test]
fn nestedElif() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    ? False { b = 1 }
    ? True {
      ? False { b = 2 }
      ? True { b = 3 }
    }
    ? { b = 9 }
    "#,
    "b", value "3"
  );
}

// =================================================================================================
// В методе.

/// Ветки возвращают значение метода через `:=`: выбранная ветка завершает метод.
#[test]
fn methodReturn() -> ()
{
  checkStructure!(
    r#"
    f(n: U8) {
      ? n = 1 { := 10 }
      ? n = 2 { := 20 }
      ? { := 30 }
    }
    r := f(1)
    "#,
    "r", value "10"
  );
  checkStructure!(
    r#"
    f(n: U8) {
      ? n = 1 { := 10 }
      ? n = 2 { := 20 }
      ? { := 30 }
    }
    r := f(2)
    "#,
    "r", value "20"
  );
  checkStructure!(
    r#"
    f(n: U8) {
      ? n = 1 { := 10 }
      ? n = 2 { := 20 }
      ? { := 30 }
    }
    r := f(3)
    "#,
    "r", value "30"
  );
}

