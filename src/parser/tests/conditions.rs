// =================================================================================================
// Результат сравнения - это `True`/`False`.

/// Само сравнение даёт `True`/`False`, а не число.
#[test]
fn comparisonResult() -> ()
{
  checkExpression!("1 < 2", type True,  value "True");
  checkExpression!("2 < 1", type False, value "False");
  checkExpression!("5 != None", type True,  value "True");
}

// =================================================================================================
// Сравнения в условии; арифметика считается раньше сравнения.

/// В условии можно писать выражения: арифметика ⟶ сравнение.
#[test]
fn expressionInCondition() -> ()
{
  // `n = 5` - это одновременно присваивание и проверка.
  checkStructure!(
    r#"
    n := 5
    b~: U8 = 0
    ? n = 5 {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    "b", value "1"
  );

  // Арифметика считается раньше сравнения: `5 + 1 > 5`.
  checkStructure!(
    r#"
    n := 5
    b~: U8 = 0
    ? n + 1 > 5 {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    "b", value "1"
  );

  checkStructure!(
    r#"
    n := 5
    b~: U8 = 0
    ? n < 3 {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    "b", value "2"
  );

  // Арифметика в обеих частях сравнения.
  checkStructure!(
    r#"
    n := 5
    b~: U8 = 0
    ? 10 / 2 = n {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    "b", value "1"
  );
}

// =================================================================================================
// Явная проверка на пустоту: `x = None` / `x != None`.

/// Пустота проверяется явно сравнением с `None`.
#[test]
fn emptiness() -> ()
{
  checkStructure!(
    r#"
    e
    b~: U8 = 0
    ? e = None {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    "b", value "1"
  );

  checkStructure!(
    r#"
    n := 5
    b~: U8 = 0
    ? n != None {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    "b", value "1"
  );

  // `n = 5`, а `None` - это не `5`, значит условие ложно.
  checkStructure!(
    r#"
    n := 5
    b~: U8 = 0
    ? n = None {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    "b", value "2"
  );

  // `0` - это не пустота.
  checkStructure!(
    r#"
    b~: U8 = 0
    ? 0 = None {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    "b", value "2"
  );
}

// =================================================================================================
// Цепочка: `False` и `None` пропускаются, берётся первый `True`.

/// Подряд идущие `?` - одна цепочка: отрабатывает первая структура с `True`.
#[test]
fn chain() -> ()
{
  // Первая структура `True` - цепочка на ней и останавливается.
  checkStructure!(
    r#"
    b~: U8 = 0
    ? True {
      b = 1
    }
    ? True {
      b = 2
    }
    ? {
      b = 3
    }
    "#,
    "b", value "1"
  );

  // Первый `False`, второй `True` - первый пропускаем.
  checkStructure!(
    r#"
    b~: U8 = 0
    ? False {
      b = 1
    }
    ? True {
      b = 2
    }
    ? {
      b = 3
    }
    "#,
    "b", value "2"
  );

  // `None` - не `True`, идём дальше; тут `True` на второй структуре.
  checkStructure!(
    r#"
    b~: U8 = 0
    ? None {
      b = 1
    }
    ? True {
      b = 2
    }
    ? {
      b = 3
    }
    "#,
    "b", value "2"
  );

  // Все условия ложные - доходим до `else`.
  checkStructure!(
    r#"
    b~: U8 = 0
    ? False {
      b = 1
    }
    ? None {
      b = 2
    }
    ? {
      b = 3
    }
    "#,
    "b", value "3"
  );
}

/// `if-elif`: `elif` выполняется, только если `if` ложный;
/// Если ложны оба - ничего не выполняется.
#[test]
fn ifElif() -> ()
{
  checkStructure!(
    r#"
    n := 1
    b~: U8 = 0
    ? n = 1 { b = 1 }
    ? n = 2 { b = 2 }
    "#,
    "b", value "1"
  );
  checkStructure!(
    r#"
    n := 2
    b~: U8 = 0
    ? n = 1 { b = 1 }
    ? n = 2 { b = 2 }
    "#,
    "b", value "2"
  );
  checkStructure!(
    r#"
    n := 3
    b~: U8 = 0
    ? n = 1 { b = 1 }
    ? n = 2 { b = 2 }
    "#,
    "b", value "0"
  );
}

// =================================================================================================
// Границы цепочки.

/// `else` завершает цепочку: `?` после него - это новая цепочка, а не `elif`.
#[test]
fn elseEndsChain() -> ()
{
  checkStructure!(
    r#"
    n := 1
    b~: U8 = 0
    ? n = 1 { b = 1 }
    ? { b = 2 }
    ? n = 1 { b = 3 }
    "#,
    "b", value "3"
  );
}

/// `else` в начале цепочки тоже завершает её: `?` после него - новая цепочка.
#[test]
fn elseFirstEndsChain() -> ()
{
  checkStructure!(
    r#"
    n := 1
    b~: U8 = 0
    ? { b = 1 }
    ? n = 1 { b = 2 }
    "#,
    "b", value "2"
  );
}

/// Обычный `else` всегда выполняется и у него нет условия.
#[test]
fn elseWithoutIf() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    ? { b = 1 }
    "#,
    "b", value "1"
  );
}

/// Строка без `?` разрывает цепочку: `?` после неё - новая цепочка, а не `elif`.
#[test]
fn lineBreaksChain() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    ? True { b = 1 }
    c := 5
    ? True { b = 2 }
    "#,
    "b", value "2"
  );
}

/// Пустое тело ветки остаётся веткой: цепочка на нём останавливается.
#[test]
fn emptyBody() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    ? True {}
    ? { b = 1 }
    "#,
    "b", value "0"
  );
  checkStructure!(
    r#"
    b~: U8 = 0
    ? False { b = 1 }
    ? {}
    "#,
    "b", value "0"
  );
}

// =================================================================================================
// Вложенность.

/// `else` вложенной цепочки принадлежит ей, а не внешней.
#[test]
fn nestedElse() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    ? True {
      ? False { b = 1 }
      ? { b = 2 }
    }
    "#,
    "b", value "2"
  );
}

/// Если во вложенной цепочке ничего не выполнилось,
/// `else` внешней цепочки всё равно пропускается.
#[test]
fn nestedSkippedKeepsOuterElse() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    ? True {
      ? False { b = 1 }
    }
    ? { b = 9 }
    "#,
    "b", value "0"
  );
}

/// Структура `else` может содержать свою цепочку.
#[test]
fn nestedInElse() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    ? False { b = 1 }
    ? {
      ? True { b = 2 }
    }
    "#,
    "b", value "2"
  );
}

/// Вложенная цепочка с `elif` не смешивается с внешней.
#[test]
fn nestedElif() -> ()
{
  checkStructure!(
    r#"
    b~: U8 = 0
    ? False { b = 1 }
    ? True {
      ? False { b = 2 }
      ? True { b = 3 }
    }
    ? { b = 9 }
    "#,
    "b", value "3"
  );
}

