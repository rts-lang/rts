// Внутри метода.

/// Ветки возвращают значение метода через `:=`: выбранная ветка завершает метод.
#[test]
fn methodReturn() -> ()
{
  checkStructure!(
    r#"
    f(n: U8) {
      ? n = 1 { := 10 }
      ? n = 2 { := 20 }
      ? { := 30 }
    }
    r := f(1)
    "#,
    "r", value "10"
  );
  checkStructure!(
    r#"
    f(n: U8) {
      ? n = 1 { := 10 }
      ? n = 2 { := 20 }
      ? { := 30 }
    }
    r := f(2)
    "#,
    "r", value "20"
  );
  checkStructure!(
    r#"
    f(n: U8) {
      ? n = 1 { := 10 }
      ? n = 2 { := 20 }
      ? { := 30 }
    }
    r := f(3)
    "#,
    "r", value "30"
  );
}

