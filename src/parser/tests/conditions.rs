// Тесты на условие `?` (`if`, `elif`, `else`).
//
//
// Структура запускается только по `True`. `False` и `None` - идём к следующей структуре.
//
// `None` - не потому что оно `False`, а потому что `?` бинарный и принимает только `True`/`False`.
//
// Если же нужна явная проверка - стоит писать `a = None`.
//
//
// Число и строка не `True` - структура не запускается.
//
//
// Как проверить, в какую структуру попал код: например можно изменить структуру выше в родителе.
//
//
// Цепочка:
//
// - `? условие { }`: `if`, самое первое условие;
//
// - `? условие { }`: `elif`, сколько угодно других условий;
//
// - `? { }`: `else` может быть после всех условий.
//
// Цепочку можно прервать через `else` или другие конструкции языка.
//
//
// `if-elif` / `else` это безымянные структуры - поэтому к ним нельзя обратиться.

// =================================================================================================
// Примитивы.

/// В условии - примитив: `True` запускает структуру, остальные идут в `else`.
#[test]
fn primitive() -> ()
{
  // Первое присваивание в переменную без значения - изнутри ветки.
  checkStructure!(
    r#"
    b~: U8
    ? True {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    "b", value "1"
  );

  checkStructure!(
    r#"
    b~: U8 = 0
    ? False {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    "b", value "2"
  );

  // `None` - это не `True`, поэтому структура не запускается.
  checkStructure!(
    r#"
    b~: U8 = 0
    ? None {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    "b", value "2"
  );

  // Число - тоже не `True`.
  checkStructure!(
    r#"
    b~: U8 = 0
    ? 1 {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    "b", value "2"
  );
}

