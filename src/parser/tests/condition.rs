// =================================================================================================
// Цепочка: False и None пропускаются, берётся первый True.

/// Подряд идущие `?` - одна цепочка: отрабатывает первый блок с True.
#[test]
fn chain() -> ()
{
  // Первый блок True - цепочка на нём и останавливается
  checkStructure!(
    r#"
    b~~ = None
    ? True {
      b = 1
    }
    ? True {
      b = 2
    }
    ? {
      b = 3
    }
    "#,
    b, value "1"
  );

  // Первый False, второй True - первый пропускаем
  checkStructure!(
    r#"
    b~~ = None
    ? False {
      b = 1
    }
    ? True {
      b = 2
    }
    ? {
      b = 3
    }
    "#,
    b, value "2"
  );

  // None - не True, идём дальше; тут True на втором блоке
  checkStructure!(
    r#"
    b~~ = None
    ? None {
      b = 1
    }
    ? True {
      b = 2
    }
    ? {
      b = 3
    }
    "#,
    b, value "2"
  );

  // Все условия ложные - доходим до else
  checkStructure!(
    r#"
    b~~ = None
    ? False {
      b = 1
    }
    ? None {
      b = 2
    }
    ? {
      b = 3
    }
    "#,
    b, value "3"
  );
}

