// Оператор создания `:=` внутри блока условия.
//
// Блок условия работает в области объемлющей структуры, поэтому `=` в нём
// меняет объявленное выше. А `:=` - наоборот: создаёт своё, здесь же.
// Это и есть то различие, ради которого у блока и у тела функции разные
// области видимости, хотя синтаксис `a = ...` у них один.
//
// todo Названия методов слишком большие.

/// `=` внутри блока меняет внешнюю структуру - блок прозрачен.
#[test]
fn blockAssignReachesOuter() -> ()
{
  checkStructure!(
    r#"
    a~ := 10
    ? True {
      a = 20
    }
    "#,
    a, value "20"
  );
}

/// `:=` внутри блока создаёт своё имя и внешнее не трогает.
#[test]
fn blockCreationStaysLocal() -> ()
{
  checkStructure!(
    r#"
    b~ := 10
    ? True {
      b~ := 20
    }
    "#,
    b, value "10"
  );
}

/// Проверка сразу двух операторов по отдельности: `:=` завёл своё имя,
/// `=` после другого блока поменял внешнее. Оба кода - по одному блоку,
/// потому что несколько блоков `?` подряд работают только для первого
/// (проверено на чистом head - там так же, это старая проблема).
#[test]
fn creationAndAssignmentSideBySide() -> ()
{
  // `:=` - создание своё, внешний `x` не тронут.
  checkStructure!(
    r#"
    x~ := 1
    ? True {
      x~ := 100
    }
    "#,
    x, value "1"
  );

  // `=` - присваивание вверх, внешний `y` поменян.
  checkStructure!(
    r#"
    y~ := 2
    ? True {
      y~ = 200
    }
    "#,
    y, value "200"
  );
}

