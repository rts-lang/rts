// Это тесты на условие `?` (issue #39) - перенос `release/logic/condition.rt`.
//
// Блок запускается только по True. False и None - идём к следующему блоку (else).
// Число и строка не True - блок тоже не запускается.
//
// Как проверить, в какой блок попал код: блок условия работает в области объемлющей
// структуры, поэтому переменная, объявленная ДО блока, меняется внутри него.
//
//     b~~ = None
//     ? True {
//       b = 1
//     }
//     ? {
//       b = 2
//     }
//
// Значит после выполнения `b` равно 1 или 2 - и это и есть ответ теста.
// Сами блоки (`if-elif` / `else`) структурами не являются и наружу не видны.
//
// Имена переменных тут b, c, d - как в condition.rt, где каждая проверка
// объявляла своё имя.

// =================================================================================================
// Примитивы.

/// В условии - примитив: True запускает блок, остальные идут в else.
#[test]
fn primitive() -> ()
{
  checkStructure!(
    r#"
    b~~ = None
    ? True {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    b, value "1"
  );

  checkStructure!(
    r#"
    b~~ = None
    ? False {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    b, value "2"
  );

  // None - это не True, поэтому блок не запускается (#39)
  checkStructure!(
    r#"
    b~~ = None
    ? None {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    b, value "2"
  );

  // Число - тоже не True
  checkStructure!(
    r#"
    b~~ = None
    ? 1 {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    b, value "2"
  );
}

