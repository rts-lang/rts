// Результат сравнения - это True/False.

/// Само сравнение даёт True/False, а не число.
#[test]
fn comparisonResult() -> ()
{
  checkExpression!("1 < 2", type TokenType::True,  value "True");
  checkExpression!("2 < 1", type TokenType::False, value "False");
  checkExpression!("5 != None", type TokenType::True,  value "True");
}

// =================================================================================================
// Сравнения в условии; арифметика считается раньше сравнения.

/// В условии можно писать выражения: арифметика -> сравнение.
#[test]
fn expressionInCondition() -> ()
{
  // n = 5 - это одновременно присваивание и проверка
  checkStructure!(
    r#"
    n = 5
    b~~ = None
    ? n = 5 {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    b, value "1"
  );

  // Арифметика считается раньше сравнения: 5 + 1 > 5
  checkStructure!(
    r#"
    n = 5
    b~~ = None
    ? n + 1 > 5 {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    b, value "1"
  );

  checkStructure!(
    r#"
    n = 5
    b~~ = None
    ? n < 3 {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    b, value "2"
  );

  // Арифметика в обеих частях сравнения
  checkStructure!(
    r#"
    n = 5
    b~~ = None
    ? 10 / 2 = n {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    b, value "1"
  );
}

