// Явная проверка на пустоту: `x = None` / `x != None`.

/// Пустота проверяется явно сравнением с None.
#[test]
fn emptiness() -> ()
{
  checkStructure!(
    r#"
    e = None
    b~~ = None
    ? e = None {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    b, value "1"
  );

  checkStructure!(
    r#"
    n = 5
    b~~ = None
    ? n != None {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    b, value "1"
  );

  // n = 5, а None - это не 5, значит условие ложно
  checkStructure!(
    r#"
    n = 5
    b~~ = None
    ? n = None {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    b, value "2"
  );

  // 0 - это не пустота
  checkStructure!(
    r#"
    b~~ = None
    ? 0 = None {
      b = 1
    }
    ? {
      b = 2
    }
    "#,
    b, value "2"
  );
}

